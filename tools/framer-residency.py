#!/usr/bin/env python3
"""Write the Residency Program's stylesheet into its Framer code component.

tools/framer/ArcoviaResidency.tsx is written by hand (markup, controls and the
port of residency.js); only its stylesheet is generated, from
site/sections/residency.css, converted the way the other ports are:
`@media (max-width)` -> `@container arc (max-width)` (each component is a size
container, so the Framer canvas shows Tablet and Phone correctly) and
`100vw` -> `100cqw`. Run it whenever residency.css changes, then upload the file
to Framer (create_upload_url, PUT, fetch() in a program, api.files.write).

    python3 tools/framer-residency.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "site/sections/residency.css"
TSX = ROOT / "tools/framer/ArcoviaResidency.tsx"


def convert(css: str) -> str:
    css = re.sub(r"@media \((max|min)-width: (\d+)px\)", r"@container arc (\1-width: \2px)", css)
    css = css.replace("100vw", "100cqw")
    # A template literal: escape backticks, backslashes and ${
    return css.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main():
    css = convert(CSS.read_text().strip())
    src = TSX.read_text()
    start = "// RESIDENCY_CSS START (generated by tools/framer-residency.py from site/sections/residency.css)\n"
    end = "// RESIDENCY_CSS END"
    a = src.index(start) + len(start)
    b = src.index(end)
    src = src[:a] + "const RESIDENCY_CSS = `" + css + "`\n" + src[b:]
    TSX.write_text(src)
    print("wrote", TSX.relative_to(ROOT))


if __name__ == "__main__":
    main()
